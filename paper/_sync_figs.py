"""Regenerate arxiv/figs.tex from manuscript.tex.

manuscript.tex is the single source of truth for the four TikZ/pgfplots
figures. This script lifts the four tikzpicture blocks out of it verbatim and
wraps them in a `standalone` document (one figure per page, tightly cropped)
so that figs.pdf -> Fig1..Fig4.pdf stay consistent with the manuscript.

A standalone document has no page, so \textwidth is undefined there. We
substitute it with a length register holding the manuscript's measured text
width, which keeps coefficient forms such as `0.92\textwidth` valid.

Run from paper/:  python _sync_figs.py
"""
import re

# \the\textwidth of elsarticle [preprint,11pt] = 360pt
PREAMBLE = r"""% figs.tex  --  AUTO-GENERATED by _sync_figs.py; do not edit by hand.
% Renders the four manuscript figures as a tightly-cropped, multi-page PDF
% (one figure per page). Compile: tectonic figs.tex   (or pdflatex)
\documentclass[crop,multi=tikzpicture,border=4pt]{standalone}
\usepackage{amsmath,amssymb}
\usepackage{bm}
\usepackage{xcolor}
\usepackage{tikz}
\usepackage{pgfplots}
\pgfplotsset{compat=1.17}
\usetikzlibrary{arrows.meta,positioning,fit,backgrounds,calc,shapes.geometric}
\usepgfplotslibrary{groupplots}

\definecolor{qpurple}{RGB}{106,61,154}
\definecolor{qblue}{RGB}{31,119,180}
\definecolor{qgreen}{RGB}{44,140,80}
\definecolor{qorange}{RGB}{214,118,32}
\definecolor{qgray}{RGB}{90,90,90}
\definecolor{lightq}{RGB}{233,226,245}
\definecolor{lightc}{RGB}{223,238,247}
\definecolor{cvviolet}{HTML}{4A3AA7}
\definecolor{cvorange}{HTML}{EB6834}
\definecolor{cvaqua}{HTML}{1BAF7A}
\definecolor{cvblue}{HTML}{2A78D6}
\newcommand{\tpr}{\mathrm{TPR}}
\newcommand{\fpr}{\mathrm{FPR}}

% stands in for the manuscript's \textwidth (elsarticle preprint, 11pt)
\newlength{\mstextwidth}
\setlength{\mstextwidth}{360pt}

\begin{document}
"""

TITLES = [
    "Figure 1: hybrid architecture",
    "Figure 2: attribution audit",
    "Figure 3: classical vs quantum F1 bars",
    "Figure 4: qubit-count ablation",
    "Figure 5: kernel bandwidth landscape",
]

src = open("manuscript.tex", encoding="utf-8").read()

blocks = re.findall(r"\\begin\{tikzpicture\}.*?\\end\{tikzpicture\}", src, re.DOTALL)
assert len(blocks) == 5, f"expected 5 tikzpictures in manuscript.tex, found {len(blocks)}"

out = [PREAMBLE]
for i, (title, blk) in enumerate(zip(TITLES, blocks), start=1):
    blk = blk.replace(r"\textwidth", r"\mstextwidth")
    out.append(f"\n% ===== Page {i}: {title} =====\n{blk}\n")
out.append("\n\\end{document}\n")

open("arxiv/figs.tex", "w", encoding="utf-8").write("".join(out))
print(f"arxiv/figs.tex regenerated from {len(blocks)} tikzpicture blocks")
